// Runs after `astro build`:
// 1. Appends redirects for long-tail pages that are planned but NOT released yet, so any link to them
//    lands on the hub calculator with that number pre-filled (302 = temporary, the page will exist later)
//    instead of a 404.
// 2. Writes the IndexNow key file when INDEXNOW_KEY is set.
import fs from 'node:fs';
const release = JSON.parse(fs.readFileSync('src/data/release.json', 'utf8'));
const range = (a, b) => Array.from({ length: b - a + 1 }, (_, i) => a + i);
const UNIVERSE = {
  'days-from-today': [...range(1, 365), 400, 500, 1000],
  'weeks-from-today': range(1, 104),
  'hours-from-now': range(1, 168),
  'days-ago': range(1, 365),
};
const expand = (spec = []) => {
  const s = new Set();
  for (const x of spec) { const m = /^(\d+)-(\d+)$/.exec(String(x)); if (m) range(+m[1], +m[2]).forEach((n) => s.add(n)); else if (/^\d+$/.test(String(x))) s.add(Number(x)); }
  return s;
};
const lines = ['', '# --- generated by scripts/postbuild.mjs: unreleased long-tail pages → hub calculator ---'];
for (const [f, all] of Object.entries(UNIVERSE)) {
  const live = expand(release[f]);
  for (const n of all) if (!live.has(n)) lines.push(`/${f}/${n}/ /${f}/?n=${n} 302`);
}
// days-until: exact rules for every planned holiday/date slug that isn't released yet
// (no wildcard: Cloudflare applies redirects even when a static page exists)
const MONTHS = ['january', 'february', 'march', 'april', 'may', 'june', 'july', 'august', 'september', 'october', 'november', 'december'];
const DIM = [31, 29, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];
const holidaySlugs = [...fs.readFileSync('src/lib/holidays.ts', 'utf8').matchAll(/slug: '([a-z0-9-]+)'/g)].map((m) => m[1]);
const dateSlugs = MONTHS.flatMap((m, i) => range(1, DIM[i]).map((d) => `${m}-${d}`));
const relU = new Set((release['days-until'] || []).map(String));
const liveU = new Set([...relU, ...(relU.has('all-holidays') ? holidaySlugs : []), ...(relU.has('all-dates') ? dateSlugs : [])]);
for (const slug of [...holidaySlugs, ...dateSlugs]) if (!liveU.has(slug)) lines.push(`/days-until/${slug}/ /days-until/ 302`);
const file = 'dist/_redirects';
const before = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
const statics = lines.filter((l) => l && !l.startsWith('#') && !l.includes('*')).length;
if (statics > 1900) console.warn(`::warning::${statics} static redirects — Cloudflare Pages allows 2,000.`);
fs.writeFileSync(file, before.trimEnd() + '\n' + lines.join('\n') + '\n');
console.log(`postbuild: ${statics} redirects for unreleased pages`);

const key = process.env.INDEXNOW_KEY;
if (key && /^[a-zA-Z0-9-]{8,128}$/.test(key)) { fs.writeFileSync(`dist/${key}.txt`, key); console.log('postbuild: IndexNow key file written'); }
